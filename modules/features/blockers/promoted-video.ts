/** 命中判定：该元素是推广标识（导出供单测与真机探针复用）。 */
export function isPromotedCardMarker(element: Element): boolean {
  if (typeof element.matches !== 'function') return false
  if (element.matches(CREATIVE_AD_SVG_SELECTOR)) return true
  if (!element.matches('path')) return false
  if (element.getAttribute('d') !== ROCKET_ICON_PATH) return false
  return element.closest('.vui_icon') !== null
}

export function createPromotedVideoBlocker(options: { root?: ParentNode } = {}): CardBlocker {
  return createCardBlocker({
    root: options.root,
    logName: 'promoted-video-blocker',
    match: isPromotedCardMarker,
    onBlocked: (count, _phase, cards) => {
      void bumpFeatureStat('promotedVideoBlocker', count)
      const events = cards
        .map((card) => cardLogEventOf(card, '推广标识'))
        .filter((event): event is NonNullable<typeof event> => event !== null)
      appendFilterLogEntries(events)
    },
  })
}
